#include <cstdio>
#include <cstring>
#include "../src/bandbox.h"
static int fails = 0;
static void expect(const char *name, const uint8_t *got, size_t n, const uint8_t *want, size_t m) {
  if (n != m || memcmp(got, want, m)) { printf("FAIL %s\n", name); fails++; } else printf("ok   %s\n", name);
}
int main() {
  uint8_t b[32];
  { size_t n = bandbox::preset(b, 3, 2);
    const uint8_t w[] = {0x00,0xDD,0x02,0x00,0x01,0x00,0x06,0x00,0x42,0x34,0x02,0x00,0x03,0x02};
    expect("preset trio 2", b, n, w, sizeof w); }
  { size_t n = bandbox::tuner(b, true);
    const uint8_t w[] = {0x00,0xDD,0x02,0x00,0x01,0x00,0x05,0x00,0x00,0x31,0x01,0x00,0x01};
    expect("tuner on", b, n, w, sizeof w); }
  { size_t n = bandbox::looperClear(b);
    const uint8_t w[] = {0x00,0xDD,0x02,0x00,0x01,0x00,0x05,0x00,0x40,0x31,0x01,0x00,0x05};
    expect("looper clear", b, n, w, sizeof w); }
  { size_t n = bandbox::looperPlay(b);
    const uint8_t w[] = {0x00,0xDD,0x02,0x00,0x01,0x00,0x05,0x00,0x45,0x31,0x01,0x00,0x03};
    expect("looper play", b, n, w, sizeof w); }
  { size_t n = bandbox::readFeature(b, 0x3100);
    const uint8_t w[] = {0x00,0xDD,0x01,0x00,0x01,0x00,0x02,0x00,0x00,0x31};
    expect("read 0x3100", b, n, w, sizeof w); }
  { size_t n = bandbox::heartbeatReply(b);
    const uint8_t w[] = {0x00,0xDD,0x04,0x00,0x01,0x00,0x04,0x00,0x02,0x00,0x00,0x00};
    expect("heartbeat reply", b, n, w, sizeof w); }
  { size_t n = bandbox::channelLevel(b, 3, 2, 16);
    const uint8_t w[] = {0x00,0xDD,0x02,0x00,0x01,0x00,0x07,0x00,0x06,0x34,0x03,0x00,0x03,0x02,0x10};
    expect("channel level", b, n, w, sizeof w); }
  return fails;
}
